def read(rel: str) -> str:
    return (RUNS / rel).read_text(encoding="utf-8").rstrip("\n")


def cut(rel: str, n: int) -> tuple[str, str]:
    """앞 n자만 싣고 잘랐다는 표시를 만든다."""
    t = read(rel)
    if len(t) <= n:
        return t, "↑ 전문입니다."
    return t[:n].rstrip() + " …", f"↑ **앞 {n}자만 실었습니다.** 실제 {len(t):,}자."


